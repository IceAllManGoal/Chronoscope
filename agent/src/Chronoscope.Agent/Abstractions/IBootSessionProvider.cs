namespace Chronoscope.Agent.Abstractions;

/// <summary>
/// Источник сведений о загрузке операционной системы (§16).
///
/// Порт, а не прямая зависимость от Windows API: сам вывод <c>boot_id</c> —
/// чистая функция от времени загрузки, и он живёт в платформенно-нейтральном
/// проекте, а конкретный способ узнать это время — платформенный. Благодаря
/// разделению <c>boot_id</c> проверяется на обычных тестах, без Windows.
/// </summary>
public interface IBootSessionProvider
{
    /// <summary>
    /// Время загрузки ОС в UTC, либо <c>null</c>, если источник не позволяет его
    /// определить.
    ///
    /// <c>null</c> — не ошибка, а честное «неизвестно»: §16 прямо допускает
    /// отсутствие <c>boot_id</c>, и подставлять вместо него догадку нельзя —
    /// выдуманный идентификатор склеил бы события разных загрузок.
    /// </summary>
    DateTimeOffset? GetBootTimeUtc();
}
