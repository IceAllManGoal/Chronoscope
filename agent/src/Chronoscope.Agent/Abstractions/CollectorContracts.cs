namespace Chronoscope.Agent.Abstractions;

/// <summary>
/// Приёмник сырых событий. Контракт из §8.3.
///
/// Намеренно синхронный и неблокирующий: коллектор обязан оставаться на связи с
/// источником событий. Если приём событий начнёт ждать доставки в Core, то
/// недоступность Core остановит наблюдение за системой — то есть отказ
/// доставки превратится в потерю данных там, где её как раз нельзя допускать.
/// Переполнение обрабатывается политикой буфера и видно в счётчиках (§34, §61).
/// </summary>
public interface IRawEventSink
{
    void Publish(Contract.RawEvent rawEvent);
}

/// <summary>
/// Коллектор — источник сырых событий. Контракт из §8.3.
///
/// Коллектор знает про источник и не знает ни про буфер, ни про транспорт, ни
/// про Core: он получает приёмник и отдаёт в него события. Границы между слоями
/// Agent держатся на этом интерфейсе.
/// </summary>
public interface IEventCollector
{
    /// <summary>Имя коллектора, попадающее в поле <c>collector</c> сырого события.</summary>
    string Name { get; }

    /// <summary>
    /// Наблюдать за источником до отмены. Метод возвращает управление только
    /// после остановки наблюдения, поэтому его ждут при завершении работы Agent.
    /// </summary>
    Task StartAsync(IRawEventSink sink, CancellationToken cancellationToken);
}
