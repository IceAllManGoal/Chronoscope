"""Индексы событий включают ``id``: сортировка списка покрыта целиком (§27, §32).

Список событий сортируется по ``timestamp DESC, id DESC`` (§32), но индексы были
построены только по ``timestamp``. SQLite пользовался ими для первой компоненты
сортировки, а остаток упорядочивал сам — ``EXPLAIN QUERY PLAN`` на запросе
страницы показывал ``USE TEMP B-TREE FOR LAST TERM OF ORDER BY``.

На обычных данных это почти незаметно: события приходят с микросекундной
точностью, и внутри одного ``timestamp`` оказывается одна-две строки. Заметно
становится там, где время повторяется — например, у источника, сообщающего время
с точностью до секунды. Измерено на настоящей схеме и настоящем запросе
репозитория, 200 000 событий с общим ``timestamp``: страница без курсора 195 мс
против 0.52, фильтр по типу 131 против 0.52, фильтр по субъекту 0.92 против 0.53.
На 200 000 событий с разными временами разница наоборот в пределах шума
(0.08 против 0.06 мс), и это тоже часть картины: индекс не «ускоряет список», он
снимает зависимость от того, насколько плотно ложатся времена.

Индексы при этом **не добавляются, а расширяются**: ``id`` дописывается в конец
четырёх существующих. §27 запрещает плодить индексы «на будущее», и это не тот
случай — набор тот же, ширина чуть больше.

Цена: индекс становится шире (``id`` — текст около 30 байт), а миграция на
существующей базе перестраивает четыре индекса целиком. Для локальной базы это
секунды; на большой истории — тем дольше, чем больше событий.
"""

from __future__ import annotations

from alembic import op

revision = "0002"
down_revision = "0001"
branch_labels = None
depends_on = None

#: Индексы после миграции: та же четвёрка, но сортировка покрыта до конца.
_COVERING = (
    ("ix_events_timestamp", ["timestamp", "id"]),
    ("ix_events_type_timestamp", ["type", "timestamp", "id"]),
    ("ix_events_actor_id_timestamp", ["actor_id", "timestamp", "id"]),
    ("ix_events_subject_id_timestamp", ["subject_id", "timestamp", "id"]),
)

#: Индексы до миграции — то, что создавала 0001.
_ORIGINAL = (
    ("ix_events_timestamp", ["timestamp"]),
    ("ix_events_type_timestamp", ["type", "timestamp"]),
    ("ix_events_actor_id_timestamp", ["actor_id", "timestamp"]),
    ("ix_events_subject_id_timestamp", ["subject_id", "timestamp"]),
)


def _recreate(indexes: tuple[tuple[str, list[str]], ...]) -> None:
    """Пересоздать индексы в заданном виде.

    Пересоздание, а не ``ALTER INDEX``: SQLite не умеет менять состав индекса.
    Имена остаются прежними, поэтому требование ruleset'а к индексам §27 —
    «индексы с такими именами существуют» — продолжает выполняться.
    """
    for name, columns in indexes:
        op.drop_index(name, table_name="events")
        op.create_index(name, "events", columns)


def upgrade() -> None:
    _recreate(_COVERING)


def downgrade() -> None:
    _recreate(_ORIGINAL)
